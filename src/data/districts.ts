// Helper: Find district by English name, Bengali name, or ID (case-insensitive)
export function findDistrict(term: string): District | undefined {
  if (!term) return undefined;
  const clean = term.trim().toLowerCase();
  return DISTRICTS.find(
    (d) =>
      d.id.toLowerCase() === clean ||
      d.nameEn.toLowerCase() === clean ||
      d.nameBn === term.trim() ||
      d.nameBn.includes(term.trim()) ||
      clean.includes(d.nameEn.toLowerCase())
  );
}

// Helper: Get counter name by district name
export function getDistrictCounterName(districtName: string, locale: 'bn' | 'en' = 'bn'): string {
  const d = findDistrict(districtName);
  if (!d) return locale === 'bn' ? 'সেন্ট্রাল বাস টার্মিনাল' : 'Central Bus Terminal';
  return locale === 'bn' ? d.counterNameBn : d.counterNameEn;
}

// Helper: Haversine distance in km between two districts
export function getDistanceBetweenDistricts(originName: string, destName: string): number {
  const d1 = findDistrict(originName) || DISTRICTS[0]; // fallback Dhaka
  const d2 = findDistrict(destName) || DISTRICTS[13]; // fallback Chattogram

  const R = 6371; // km
  const dLat = ((d2.lat - d1.lat) * Math.PI) / 180;
  const dLon = ((d2.lng - d1.lng) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((d1.lat * Math.PI) / 180) *
      Math.cos((d2.lat * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const straightLine = R * c;

  // Road factor: Highways in Bangladesh have ~1.3x - 1.4x road curvature
  const roadKm = Math.max(50, Math.round(straightLine * 1.38));
  return roadKm;
}

// Estimate highway travel duration in minutes
export function getDurationMinutes(distanceKm: number): number {
  // Average highway speed ~ 45-50 km/h with stops
  const hours = distanceKm / 46;
  return Math.round(hours * 60);
}

